// Re-bake src/pixel-pieces.js from the sculpted models in the dev server.
// Usage: start `npm run dev`, then `node scripts/bake-pixels.mjs`.
import { chromium } from '@playwright/test';
import { writeFileSync } from 'node:fs';
const url = process.env.PIECEGEN_URL || 'http://127.0.0.1:5197/tools/piecegen.html';
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 600, height: 400 } });
await page.goto(url, { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.ready === true);
const sprites = await page.evaluate(() => window.bake());
const types = ['p', 'n', 'b', 'r', 'q', 'k'];
let out = '// Generated by scripts/bake-pixels.mjs. 32x32 pixel-art renders of the sculpted pieces.\n';
out += 'export const PIXEL_SIZE=32;\n';
out += "export const PIXEL_PALETTES={w:['#1b1512','#6f5b40','#a8926b','#cdbb95','#e9ddc2','#fff8e8','#d8b46a'],b:['#05070a','#141c23','#24313a','#3a4a55','#5c6d77','#93a5ac','#d8b46a']};\n";
out += 'export const PIXEL_PIECES={\n';
for (const color of ['w', 'b']) {
 out += ` ${color}:{\n`;
 for (const type of types) {
  const rows = sprites[`${type}${color}`].rows;
  out += `  ${type}:[\n${rows.map(r => `   '${r}'`).join(',\n')}\n  ],\n`;
 }
 out += ' },\n';
}
out += '};\n';
writeFileSync('src/pixel-pieces.js', out);
await browser.close();
console.log('Baked', out.length, 'characters into src/pixel-pieces.js');
