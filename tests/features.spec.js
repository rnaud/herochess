import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{await page.addInitScript(()=>{try{localStorage.setItem('herochess-coach-v1','done');}catch{}});});
test('Arcana Trial solves, saves the star and offers the next position',async({page})=>{
 await page.goto('/');
 await page.locator('#trials-header').click();
 await expect(page.locator('.trial-item')).toHaveCount(6);
 await page.locator('.trial-item').first().click();
 await expect(page.locator('#trial-banner')).toBeVisible();
 await expect(page.locator('#trial-name')).toHaveText('The Long Road');
 await page.locator('#hand .spell-card').first().click();
 await page.locator('[data-square="12"]').click();
 await page.locator('[data-square="60"]').click();
 await expect(page.locator('#promotion-dialog')).toBeVisible();
 await page.locator('#promotion-options button').first().click();
 await expect(page.locator('#status-title')).toHaveText('Trial solved.',{timeout:8000});
 await expect(page.locator('#trial-feedback')).toContainText('Mate found');
 await expect(page.locator('#trial-next')).toBeVisible();
 await expect(page.locator('#result-dialog')).toBeHidden();
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('herochess-trials-v1')||'[]'))).toContain('tower');
 await page.locator('#trial-next').click();
 await expect(page.locator('#trial-name')).toHaveText('Homeward Bound');
});
test('Match Review walks the saved timeline without changing the game',async({page})=>{
 await page.goto('/');
 await page.locator('[data-square="12"]').click();
 await page.locator('[data-square="28"]').click();
 await expect(page.locator('#move-count')).toHaveText('02',{timeout:15000});
 await page.locator('#review-button').click();
 await expect(page.locator('#review-dialog')).toBeVisible();
 await expect(page.locator('#review-slider')).toHaveAttribute('max','2');
 await expect(page.locator('.review-move')).toHaveCount(3);
 await expect(page.locator('#review-step-count')).toHaveText('2 / 2');
 await page.locator('#review-prev').click();
 await expect(page.locator('#review-step-count')).toHaveText('1 / 2');
 await page.locator('#review-list .review-move').first().click();
 await expect(page.locator('#review-step-count')).toHaveText('0 / 2');
 await page.locator('#review-close').click();
 await expect(page.locator('#review-dialog')).toBeHidden();
 await expect(page.locator('#move-count')).toHaveText('02');
});
test('career record and threat radar expose saved milestones and live pressure',async({page})=>{
 await page.addInitScript(()=>{try{localStorage.setItem('herochess-stats-v1',JSON.stringify({games:12,wins:7,losses:5,draws:0,streak:2,bestStreak:4,cards:{tower:3,frost:2,comet:1},levels:{2:12},matches:[{date:'2026-11-01',outcome:'win',mode:'cards',level:2,moves:44,powers:['tower'],reason:'Checkmate',daily:false}],checkmates:2,flawlessWins:1,daily:{date:'2026-11-05',streak:3,wins:4}}));}catch{}});
 await page.goto('/');
 await page.locator('#record-header').click();
 await expect(page.locator('#record-body')).toContainText('58%');
 await expect(page.locator('#record-body')).toContainText('Tower Road');
 await expect(page.locator('#record-body')).toContainText('Nov 1');
 await page.locator('#record-close').click();
 await page.locator('#radar-button').click();
 await expect(page.locator('#radar-button')).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('#radar-chip')).toContainText('THREAT RADAR');
 expect(await page.locator('.flat-square.threat').count()).toBeGreaterThan(0);
 await page.locator('#radar-button').click();
 await expect(page.locator('#radar-chip')).toBeHidden();
});
test('ambient score is opt-in and persists while the audio mixer stays available',async({page})=>{
 await page.goto('/');
 await page.locator('#guide-button').click();
 await expect(page.locator('#music-toggle')).not.toBeChecked();
 await page.locator('#music-toggle').check();
 await expect(page.locator('#music-toggle')).toBeChecked();
 await page.locator('#music-volume').evaluate(el=>{el.value='35';el.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.locator('#guide-dialog .close-dialog').click();
 await page.reload();
 await page.locator('#guide-button').click();
 await expect(page.locator('#music-toggle')).toBeChecked();
 await expect(page.locator('#music-volume')).toHaveValue('35');
 await page.locator('#music-toggle').uncheck();
 await expect(page.locator('#music-toggle')).not.toBeChecked();
});
